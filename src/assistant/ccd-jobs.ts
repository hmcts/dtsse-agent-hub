import { CCD_CONFIGS } from "@hmcts-cft/bulk-scan-spec/schema";
import { z } from "zod";
import { boundedArray } from "../agent-api/bounded-array.ts";
import { definePodJobKind } from "./pod-jobs.ts";

/**
 * The Bulk Scan builder's two pod jobs: the CCD case types the person's workspace clone knows, and the case fields of one.
 * Both run the workspace's `scripts/ccd-case-types` on the conversation's own pod, against its own clones, because the
 * definitions live in repositories only that pod has. See "CCD case types" in docs/agent-api.md.
 */

export const MAX_LISTED_CASE_TYPES = 500;
/** The most case fields one answer carries. */
export const MAX_CASE_TYPE_FIELDS = 20_000;
/**
 * What the pod's answer may hold of the fields, in JSON bytes. It is under the hub's cap on a result (1 MiB,
 * `MAX_POD_JOB_RESULT_BYTES`), and the upload carries the same JSON beside a form of up to 5 MiB: the route allows it
 * this many bytes and 64 KiB of framing, which keeps the whole body under the proxy's 6 MiB.
 */
export const MAX_FIELDS_BYTES = 900_000;

export const CCD_JOB_ERRORS = [
  "script_missing",
  "tool_missing",
  "unknown_case_type",
  "ambiguous_case_type",
  "not_cloned",
  "generation_failed",
  "unreadable"
] as const;

export const CASE_TYPE_ID = /^[A-Za-z0-9][A-Za-z0-9_.-]{0,99}$/;
export const PRODUCT = /^[a-z][a-z0-9-]{0,39}$/;
/** A repository's path in the workspace: two to four segments, such as `apps/sptribs/sptribs-case-api`. */
export const REPO_PATH = /^[A-Za-z0-9][A-Za-z0-9_.-]{0,59}(\/[A-Za-z0-9][A-Za-z0-9_.-]{0,59}){1,3}$/;

export const CCD_CASE_TYPES = definePodJobKind({
  kind: "ccd.case-types",
  args: z.strictObject({}),
  result: z.strictObject({
    case_types: boundedArray(
      z.strictObject({
        product: z.string().regex(PRODUCT),
        service: z.string().max(100),
        case_type: z.string().regex(CASE_TYPE_ID),
        config: z.enum(CCD_CONFIGS).nullable().catch(null),
        repo: z.string().regex(REPO_PATH).optional().catch(undefined)
      }),
      MAX_LISTED_CASE_TYPES,
      { message: `at most ${MAX_LISTED_CASE_TYPES} case types` }
    )
  }),
  errors: CCD_JOB_ERRORS,
  timeoutMs: 60_000,
  rateLimit: { limit: 30, windowMs: 60_000 },
  maxResultBytes: 256 * 1024
});

const fieldRow = z.strictObject({
  ID: z.string().min(1).max(300),
  Label: z.string().max(200).optional(),
  FieldType: z.string().min(1).max(60),
  FieldTypeParameter: z.string().max(100).optional(),
  HintText: z.string().max(200).optional()
});

/** The fields as the job answers them, and as the browser returns them with an upload. */
export const CCD_FIELD_ROWS = boundedArray(fieldRow, MAX_CASE_TYPE_FIELDS, { message: `at most ${MAX_CASE_TYPE_FIELDS} fields` });

export const CCD_CASE_TYPE_FIELDS = definePodJobKind({
  kind: "ccd.case-type-fields",
  args: z.strictObject({ case_type: z.string().regex(CASE_TYPE_ID), product: z.string().regex(PRODUCT).optional() }),
  result: z.strictObject({
    fields: CCD_FIELD_ROWS,
    /** Rows the definition has, label rows and all. */
    total: z.number().int().min(0),
    /** Fields left out only to fit the answer; the label rows are always left out and are not counted. */
    omitted: z.number().int().min(0)
  }),
  errors: CCD_JOB_ERRORS,
  // A config-generator service's definition is generated by Gradle when it is out of date: 15 to 35 seconds.
  timeoutMs: 180_000,
  rateLimit: { limit: 20, windowMs: 60_000 },
  maxResultBytes: 1024 * 1024
});
