// Renders the installed app's icons from the Assistant's mark into src/app/pwa-icon/icons.ts, as base64 PNGs.
//
//   node scripts/pwa-icons.mjs
//
// Committed rather than built, and embedded rather than served from `public/`, so the image has no file to trace and
// nothing to copy. The mark is white on the Assistant's dark background with the colours fixed: the browser-tab icon
// (`src/app/assistant/icon.svg`) switches colour with the browser's theme, and on a launcher it came out as nothing
// at all, because a transparent icon has no background to be seen against.
// `sharp` is not a dependency of its own: Next installs it for image optimisation, which is what this borrows.
import { readFileSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const BACKGROUND = "#0b0c0c";
const source = readFileSync(new URL("../src/app/assistant/icon.svg", import.meta.url), "utf8");
const mark = [...source.matchAll(/<(?:path|circle)\b[^>]*\/>/g)].map((match) => match[0]).join("");

/**
 * `fraction` of the square is the mark, centred and nudged up two source units, because the crown's weight is in its
 * lower half and it reads as sitting low when its box is centred. `rounded` draws the corners for icons the system
 * does not mask itself.
 */
function svg(size, fraction, rounded) {
  const scale = (size * fraction) / 64;
  const offset = (size - 64 * scale) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
  <rect width="${size}" height="${size}" rx="${rounded ? size * 0.2 : 0}" fill="${BACKGROUND}"/>
  <g fill="#ffffff" transform="translate(${offset} ${offset - 2 * scale}) scale(${scale})">${mark}</g>
</svg>`;
}

const icons = {
  "192.png": svg(192, 0.62, true),
  "512.png": svg(512, 0.62, true),
  // Android masks this to a circle or a squircle, keeping the middle 80%: the mark has to sit well inside it.
  "maskable-512.png": svg(512, 0.46, false),
  // iOS rounds the corners itself, and fills any transparency with black.
  "180.png": svg(180, 0.62, false)
};

const entries = [];
for (const [name, markup] of Object.entries(icons)) {
  const png = await sharp(Buffer.from(markup)).png({ compressionLevel: 9 }).toBuffer();
  entries.push(`  "${name}": "${png.toString("base64")}"`);
}
writeFileSync(
  new URL("../src/app/pwa-icon/icons.ts", import.meta.url),
  `// Generated by scripts/pwa-icons.mjs; do not edit.\nexport const ICONS: Readonly<Record<string, string>> = {\n${entries.join(",\n")}\n};\n`
);
