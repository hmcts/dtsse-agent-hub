describe("readCapped", () => {
  function streamOf(chunks: number[]): ReadableStream<Uint8Array> {
    return new ReadableStream({
      start(controller) {
        for (const size of chunks) {
          controller.enqueue(new Uint8Array(size));
        }
        controller.close();
      }
    });
  }

  it("should read the whole body when it is within the cap", async () => {
    expect((await readCapped(streamOf([3, 4]), 10, vi.fn())).length).toBe(7);
  });

  it("should abort the download as soon as it passes the cap, whatever content-length said", async () => {
    const abort = vi.fn();

    await expect(readCapped(streamOf([6, 6, 6]), 10, abort)).rejects.toThrow("over the 10 bytes");
    expect(abort).toHaveBeenCalledOnce();
  });
});

