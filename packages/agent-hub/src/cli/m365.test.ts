describe("m365 calendar paging", () => {
  it("should follow Graph's next-page links and say there is more when it stops at its cap", async () => {
    const page = (n: number, next: boolean) => ({
      value: Array.from({ length: n }, (_, i) => ({ id: `e${i}` })),
      ...(next ? { "@odata.nextLink": "https://graph.microsoft.com/v1.0/me/calendarView?$skiptoken=x" } : {})
    });
    const fetchImpl = vi.fn(async () => new Response(JSON.stringify(page(50, true))));
    const { cli, out } = cliWith(vi.fn(async () => TOKEN));

    await fresh(fetchImpl as unknown as typeof fetch)(cli, ["calendar"]);

    expect(fetchImpl).toHaveBeenCalledTimes(MAX_EVENTS / 50);
    expect(JSON.parse(out.join(""))).toMatchObject({ truncated: true, more: true });
    expect(JSON.parse(out.join("")).data).toHaveLength(MAX_EVENTS);
  });

  it("should not say there is more when the last page came in under the cap", async () => {
    const fetchImpl = vi
      .fn()
      .mockResolvedValueOnce(new Response(JSON.stringify({ value: [{ id: "e1" }], "@odata.nextLink": "https://graph.microsoft.com/v1.0/next" })))
      .mockResolvedValueOnce(new Response(JSON.stringify({ value: [{ id: "e2" }] })));
    const { cli, out } = cliWith(vi.fn(async () => TOKEN));

    await fresh(fetchImpl as unknown as typeof fetch)(cli, ["calendar"]);

    expect(JSON.parse(out.join("")).more).toBeUndefined();
    expect(JSON.parse(out.join("")).data).toHaveLength(2);
  });
});

describe("the m365 token cache", () => {
  it("should mint once and use the token again from memory while it has time left", async () => {
    const microsoftToken = vi.fn(async () => TOKEN);
    const memory = new Map();
    const { cli } = cliWith(microsoftToken);

    await fresh(graphAnswering({ value: [] }) as unknown as typeof fetch, () => NOW, memory)(cli, ["teams", "list"]);
    await fresh(graphAnswering({ value: [] }) as unknown as typeof fetch, () => NOW, memory)(cli, ["teams", "list"]);

    expect(microsoftToken).toHaveBeenCalledOnce();
  });

  it("should keep the token in a 0600 file per agent, which another process uses without minting", async () => {
    const pod = { AGENT_HUB_VIRTUAL_AGENT_ID: "va-1", AGENT_HUB_LAUNCH_TOKEN: "launch" };
    const { cli } = cliWith(
      vi.fn(async () => TOKEN),
      pod
    );
    await fresh(graphAnswering({ value: [] }) as unknown as typeof fetch)(cli, ["teams", "list"]);
    const file = tokenFile(pod);

    expect(file).toBe(path.join(home, "agent-hub", "m365-token-va-1.json"));
    expect(fs.statSync(file).mode & 0o777).toBe(0o600);
    expect(tokenFile({})).toBe(path.join(home, "agent-hub", "m365-token-person.json"));

    const again = vi.fn(async () => TOKEN);
    await fresh(graphAnswering({ value: [] }) as unknown as typeof fetch)(cliWith(again, pod).cli, ["teams", "list"]);
    expect(again).not.toHaveBeenCalled();
  });

  it("should mint again when the saved token is within the margin of expiring", async () => {
    const microsoftToken = vi.fn(async () => TOKEN);
    const { cli } = cliWith(microsoftToken);
    const nearlyOver = () => Date.parse(TOKEN.expires_at) - TOKEN_MARGIN_MS + 1;

    await fresh(graphAnswering({ value: [] }) as unknown as typeof fetch, nearlyOver)(cli, ["teams", "list"]);
    await fresh(graphAnswering({ value: [] }) as unknown as typeof fetch, nearlyOver)(cli, ["teams", "list"]);

    expect(microsoftToken).toHaveBeenCalledTimes(2);
  });
});

