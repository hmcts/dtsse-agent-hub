const TOKEN = { access_token: "graph-access", expires_at: "2026-12-01T09:59:00.000Z", permissions: ["Mail.Read"] };
const NOW = Date.parse("2026-12-01T09:00:00.000Z");

/** A command with a token memory of its own, on the test's clock unless one is given. */
function fresh(fetchImpl?: typeof fetch, now: () => number = () => NOW, memory = new Map()) {
  return m365Command(fetchImpl, now, memory);
}

