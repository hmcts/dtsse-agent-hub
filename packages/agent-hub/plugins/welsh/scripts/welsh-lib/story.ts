/**
 * The "Welsh content" section of a Jira story.
 *
 * English strings are *selected* from the story (by rule, or confirmed by a
 * BA) and must appear in it verbatim. Their Welsh is either an approved
 * catalogue rendering or a REQUIRED placeholder — never anything else.
 */

import { type Catalogue, lookup, type Row } from "./catalogue.ts";
import { type AdfNode, adfText } from "./jira.ts";
import { matchKey } from "./normalise.ts";
import { contentRef } from "./requests.ts";
import { isPlaceholder, MARKER } from "./verify.ts";

export const SECTION_TITLE = "Welsh content";
const SECTION_NOTE =
  "Generated by the CFT Welsh tooling. Welsh comes only from the Welsh Language Unit, via the service's translation catalogue. " +
  "Rows marked WELSH TRANSLATION REQUIRED have been sent to the WLU; do not fill them in by hand or with AI.";
const HEADERS = ["Ref", "English", "Welsh", "Source"];

/**
 * Strings that look like user-facing content. A starting point for the BA,
 * not a decision: they confirm the list before anything is built.
 */
export function candidates(doc: AdfNode): Candidate[] {
  const found = new Map<string, Candidate>();
  const add = (text: string, origin: Candidate["origin"]) => {
    const t = text.trim();
    if (!/\p{L}/u.test(t) || t.length > 2000) {
      return;
    }
    const k = matchKey(t);
    if (!found.has(k)) {
      found.set(k, { english: t, origin });
    }
  };

  // Prose lines across the whole story, in order: content often sits in the
  // paragraph *after* the Gherkin step that introduces it.
  const lines: string[] = [];
  for (const node of withoutWelshSection(doc).content ?? []) {
    if (node.type === "table") {
      for (const text of englishColumn(node)) {
        add(text, "table");
      }
      continue;
    }
    lines.push(...adfText(node).split("\n"));
  }
  for (const line of lines) {
    for (const m of line.matchAll(/[“"]([^“”"]{2,})[”"]/g)) {
      add(m[1], "quoted");
    }
  }
  // Gherkin: "Then the following option is shown:" followed by the content lines.
  for (let i = 0; i < lines.length; i++) {
    if (!/\bfollowing\b.*\b(is|are)\s+(shown|displayed)\s*:\s*$/i.test(lines[i])) {
      continue;
    }
    for (let j = i + 1; j < lines.length && lines[j].trim() && !GHERKIN.test(lines[j]); j++) {
      add(lines[j].trim().replace(/^[“"](.*)[”"]$/s, "$1"), "after-shown");
    }
  }
  return [...found.values()];
}

const GHERKIN = /^\s*(Given|When|Then|And|But|AC\s*\d+|Scenario)\b/i;

/** English strings that are not in the story text — the BA list must come from the story. */
export function notInStory(strings: string[], doc: AdfNode): string[] {
  const text = matchKey(adfText(withoutWelshSection(doc)));
  return strings.filter((s) => !text.includes(matchKey(s)));
}

/**
 * Build the table rows. Existing rows keep their Welsh if it is still
 * traceable; placeholders are refilled when the catalogue now has an answer.
 */
export function buildRows(
  service: string,
  strings: string[],
  catalogue: Catalogue,
  existing: StoryRow[],
  choices: Map<string, Row>,
  sensitive: string[] = []
): BuildResult {
  const prior = new Map(existing.map((r) => [matchKey(r.english), r]));
  const rows: StoryRow[] = [];
  const handEdited: StoryRow[] = [];
  for (const english of strings) {
    const ref = contentRef(service, english);
    const chosen = choices.get(ref);
    const found = lookup(english, catalogue, sensitive);
    const before = prior.get(matchKey(english));

    if (chosen) {
      rows.push({ ref, english, welsh: chosen.welsh, source: `${chosen.source} (BA choice, row ${chosen.id})`, state: "filled" });
    } else if (found.kind === "hit") {
      rows.push({ ref, english, welsh: found.welsh, source: `catalogue:${found.catalogue} ${found.row.source}`, state: "filled" });
    } else if (before && !isPlaceholder(before.welsh)) {
      // Welsh in the story that the catalogue can't account for: someone typed it.
      handEdited.push(before);
      rows.push({ ...before, ref, state: "hand-edited" });
    } else if (found.kind === "ambiguous") {
      rows.push({
        ref,
        english,
        welsh: MARKER(english),
        source: `${found.options.length} catalogue options — BA to choose`,
        state: "ambiguous",
        options: found.options.map((o) => ({ id: o.id, welsh: o.welsh, context: o.context, source: o.source }))
      });
    } else {
      rows.push({ ref, english, welsh: MARKER(english), source: "Sent to WLU", state: "required" });
    }
  }
  return { rows, handEdited };
}

/** Rows of an existing generated section, if the story has one. */
export function existingRows(doc: AdfNode): StoryRow[] {
  const section = findSection(doc);
  if (!section) {
    return [];
  }
  const table = (doc.content ?? []).slice(section.start, section.end).find((n) => n.type === "table");
  if (!table) {
    return [];
  }
  return (table.content ?? []).slice(1).map((tr) => {
    const [ref, english, welsh, source] = (tr.content ?? []).map((c) => adfText(c).trim());
    return { ref, english, welsh, source, state: "filled" as const };
  });
}

/** The story with its Welsh section replaced (or appended), everything else untouched. */
export function withSection(doc: AdfNode, rows: StoryRow[]): AdfNode {
  const content = [...(doc.content ?? [])];
  const section = findSection(doc);
  const nodes = sectionNodes(rows);
  if (section) {
    content.splice(section.start, section.end - section.start, ...nodes);
  } else {
    content.push(...nodes);
  }
  return { ...doc, content };
}

export function markdownPreview(rows: StoryRow[]): string {
  const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, "<br>");
  return [
    `| ${HEADERS.join(" | ")} |`,
    `|${HEADERS.map(() => "---").join("|")}|`,
    ...rows.map((r) => `| ${[r.ref, r.english, r.welsh, r.source].map(cell).join(" | ")} |`)
  ].join("\n");
}

function sectionNodes(rows: StoryRow[]): AdfNode[] {
  const text = (t: string, marks?: AdfNode["marks"]): AdfNode => ({ type: "text", text: t, ...(marks ? { marks } : {}) });
  const para = (t: string): AdfNode => {
    const parts = t.split("\n");
    const content: AdfNode[] = [];
    parts.forEach((p, i) => {
      if (i) {
        content.push({ type: "hardBreak" });
      }
      if (p) {
        content.push(text(p));
      }
    });
    return { type: "paragraph", content };
  };
  const cell = (t: string, header = false): AdfNode => ({ type: header ? "tableHeader" : "tableCell", content: [para(t)] });
  return [
    { type: "heading", attrs: { level: 2 }, content: [text(SECTION_TITLE)] },
    { type: "paragraph", content: [text(SECTION_NOTE, [{ type: "em" }])] },
    {
      type: "table",
      attrs: { isNumberColumnEnabled: false, layout: "default" },
      content: [
        { type: "tableRow", content: HEADERS.map((h) => cell(h, true)) },
        ...rows.map((r) => ({ type: "tableRow", content: [r.ref, r.english, r.welsh, r.source].map((t) => cell(t)) }))
      ]
    }
  ];
}

/** Index range of the generated section: its heading up to the next heading of the same or higher level. */
function findSection(doc: AdfNode): { start: number; end: number } | null {
  const content = doc.content ?? [];
  const start = content.findIndex((n) => n.type === "heading" && adfText(n).trim() === SECTION_TITLE);
  if (start < 0) {
    return null;
  }
  const level = Number(content[start].attrs?.level ?? 2);
  let end = start + 1;
  while (end < content.length && !(content[end].type === "heading" && Number(content[end].attrs?.level ?? 2) <= level)) {
    end++;
  }
  return { start, end };
}

function withoutWelshSection(doc: AdfNode): AdfNode {
  const section = findSection(doc);
  if (!section) {
    return doc;
  }
  const content = [...(doc.content ?? [])];
  content.splice(section.start, section.end - section.start);
  return { ...doc, content };
}

/** Cells of a table's English column (header "English", "Content", "Text"…), skipping tables that already have Welsh. */
function englishColumn(table: AdfNode): string[] {
  const [head, ...body] = table.content ?? [];
  const headers = (head?.content ?? []).map((c) => adfText(c).trim());
  if (headers.some((h) => /welsh|cymraeg/i.test(h))) {
    return [];
  }
  const col = headers.findIndex((h) => /^(english|en|content|text|copy|wording)\b/i.test(h));
  if (col < 0) {
    return [];
  }
  return body.map((tr) => adfText((tr.content ?? [])[col] ?? { type: "text", text: "" })).filter(Boolean);
}

export interface Candidate {
  english: string;
  origin: "table" | "quoted" | "after-shown";
}

export interface StoryRow {
  ref: string;
  english: string;
  welsh: string;
  source: string;
  state: "filled" | "required" | "ambiguous" | "hand-edited";
  options?: { id: string; welsh: string; context: string; source: string }[];
}

export interface BuildResult {
  rows: StoryRow[];
  handEdited: StoryRow[];
}
